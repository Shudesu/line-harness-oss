import { describe, expect, it } from 'vitest'
import {
  DEV_BUNDLE_VERSION,
  parseBundleVersion,
  resolveBuildAppVersion,
  resolveDisplayVersion,
} from './app-version'

const STAMPED = `// AUTO-GENERATED by scripts/inject-version.ts — do not edit.
export const BUNDLE_VERSION = '0.26.2-replay.wallet.20261101.3';
export const WORKER_HASH = 'sha256:aa';
`

const DEV_STUB = `// AUTO-GENERATED by scripts/inject-version.ts — do not edit (this is the dev stub).
export const BUNDLE_VERSION = '0.0.0-dev';
`

describe('parseBundleVersion', () => {
  it('reads the stamped BUNDLE_VERSION out of _version.ts', () => {
    expect(parseBundleVersion(STAMPED)).toBe('0.26.2-replay.wallet.20261101.3')
  })

  it('treats the dev stub as "no version"', () => {
    expect(parseBundleVersion(DEV_STUB)).toBeNull()
  })

  it('returns null when the file is missing or has no constant', () => {
    expect(parseBundleVersion(null)).toBeNull()
    expect(parseBundleVersion('export const WORKER_HASH = "sha256:aa";')).toBeNull()
  })

  it('reads the double-quoted form inject-version.ts actually emits', () => {
    expect(parseBundleVersion('export const BUNDLE_VERSION = "0.8.0";')).toBe('0.8.0')
  })
})

describe('resolveBuildAppVersion', () => {
  it('uses the CI bundle version instead of the root package.json version', () => {
    expect(
      resolveBuildAppVersion({
        env: { CLOUD_BUNDLE_VERSION: '0.26.2-replay.wallet.20261101.3' },
        versionModuleSource: DEV_STUB,
        packageVersion: '0.26.1',
      }),
    ).toBe('0.26.2-replay.wallet.20261101.3')
  })

  it('lets an explicit APP_VERSION win over everything else', () => {
    expect(
      resolveBuildAppVersion({
        env: { APP_VERSION: '9.9.9', CLOUD_BUNDLE_VERSION: '0.26.2' },
        versionModuleSource: STAMPED,
        packageVersion: '0.26.1',
      }),
    ).toBe('9.9.9')
  })

  it('falls back to a stamped _version.ts when CI did not pass the version', () => {
    expect(
      resolveBuildAppVersion({
        env: {},
        versionModuleSource: STAMPED,
        packageVersion: '0.26.1',
      }),
    ).toBe('0.26.2-replay.wallet.20261101.3')
  })

  it('falls back to the root package.json version for self-hosted builds', () => {
    expect(
      resolveBuildAppVersion({
        env: {},
        versionModuleSource: DEV_STUB,
        packageVersion: '0.26.1',
      }),
    ).toBe('0.26.1')
    expect(
      resolveBuildAppVersion({ env: {}, packageVersion: '0.26.1' }),
    ).toBe('0.26.1')
  })

  it('ignores blank env values rather than baking an empty version', () => {
    expect(
      resolveBuildAppVersion({
        env: { APP_VERSION: '  ', CLOUD_BUNDLE_VERSION: '  ' },
        versionModuleSource: null,
        packageVersion: '0.26.1',
      }),
    ).toBe('0.26.1')
  })
})

describe('resolveDisplayVersion', () => {
  it('prefers the version the running Worker reports', () => {
    expect(resolveDisplayVersion('0.26.0', '0.26.2-replay.wallet.20261101.3')).toBe(
      '0.26.2-replay.wallet.20261101.3',
    )
  })

  it('keeps the build-time version until /admin/version resolves', () => {
    expect(resolveDisplayVersion('0.26.0', null)).toBe('0.26.0')
    expect(resolveDisplayVersion('0.26.0', undefined)).toBe('0.26.0')
  })

  it('keeps the build-time version for an unstamped Worker', () => {
    expect(resolveDisplayVersion('0.26.0', DEV_BUNDLE_VERSION)).toBe('0.26.0')
    expect(resolveDisplayVersion('0.26.0', '  ')).toBe('0.26.0')
  })
})
