import { describe, expect, it } from 'vitest';
import { issueIgLinkToken, verifyIgLinkToken, IG_LINK_TOKEN_TTL } from '@line-crm/shared';
import { igLinkVectors as vector } from '../test-support/ig-link-vectors.js';

const env = { IG_LINK_TOKEN_SECRET: 'synthetic-direct-secret' };
const now = vector.now;
const seconds = now / 1000;
const payload = { v: 1, igsid: 'test-igsid', iga: 'test-iga', exp: seconds + 3600, n: 'AAECAwQFBgcICQoLDA0ODw' };
async function sign(value: unknown, raw?: string) {
  const part = Buffer.from(raw ?? JSON.stringify(value)).toString('base64url');
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(env.IG_LINK_TOKEN_SECRET), {name:'HMAC',hash:'SHA-256'}, false, ['sign']);
  const signature = await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(part));
  return part+'.'+Buffer.from(signature).toString('base64url');
}
describe('IG link token verifier', () => {
  it('round trips both key paths, including Unicode and optional iga', async () => {
    for (const binding of [env, {IG_HARNESS_LINK_SECRET:'synthetic-shared-secret'}]) {
      const token = await issueIgLinkToken(binding,'synthetic-igsid','テスト',now);
      expect(await verifyIgLinkToken(binding,token,now)).toMatchObject({v:1,igsid:'synthetic-igsid',iga:'テスト',exp:seconds+IG_LINK_TOKEN_TTL});
      expect((await verifyIgLinkToken(binding,await issueIgLinkToken(binding,'synthetic-igsid',undefined,now),now))?.iga).toBeUndefined();
    }
  });
  it('accepts pinned tokens generated by the IG implementation for HKDF and direct keys', async () => {
    expect(await verifyIgLinkToken({IG_HARNESS_LINK_SECRET:vector.secret}, vector.hkdf, now)).toMatchObject({igsid:'test-igsid',iga:'test-iga',n:payload.n});
    expect(await verifyIgLinkToken({IG_LINK_TOKEN_SECRET:vector.secret,IG_HARNESS_LINK_SECRET:'ignored-fake-secret'}, vector.direct, now)).toMatchObject({igsid:'test-igsid',iga:'test-iga',n:payload.n});
    expect(await verifyIgLinkToken({IG_LINK_TOKEN_SECRET:vector.secret}, vector.hkdf, now)).toBeNull();
  });
  it('rejects tampered signatures and payloads', async () => {
    const token = await sign(payload);
    const [part, sig] = token.split('.');
    const corrupt = Buffer.from(sig!, 'base64url'); corrupt[0] ^= 1;
    expect(await verifyIgLinkToken(env, part+'.'+corrupt.toString('base64url'),now)).toBeNull();
    expect(await verifyIgLinkToken(env, Buffer.from(JSON.stringify({...payload,igsid:'forged'})).toString('base64url')+'.'+sig,now)).toBeNull();
  });
  it.each([
    {exp:seconds}, {exp:seconds-1}, {exp:seconds+IG_LINK_TOKEN_TTL+1}, {exp:seconds+0.5}, {exp:'1800000001'},
    {v:2}, {v:'1'}, {n:'short'}, {n:'A'.repeat(21)+'B'}, {n:'='.repeat(22)}, {n:42},
    {igsid:''}, {igsid:42}, {igsid:'x'.repeat(129)}, {iga:42}, {iga:'x'.repeat(129)},
  ])('rejects a correctly signed invalid claim (%j)', async patch => {
    expect(await verifyIgLinkToken(env,await sign({...payload,...patch}),now)).toBeNull();
  });
  it('rejects malformed JSON, noncanonical base64url, wrong types and oversized tokens', async () => {
    const token = await sign(payload);
    for (const input of [null,42,{},'',token+'.x',token+'=',token.replace('.', '=.'),'x'.repeat(8193),await sign(null),await sign(null,'{')]) {
      expect(await verifyIgLinkToken(env,input,now)).toBeNull();
    }
    expect(await verifyIgLinkToken(env,await sign(payload),now)).not.toBeNull();
  });
  it('missing secrets and wrong secrets fail closed without throwing', async () => {
    expect(await issueIgLinkToken({},'test-igsid',undefined,now)).toBeNull();
    const token = await sign(payload);
    expect(await verifyIgLinkToken({},token,now)).toBeNull();
    expect(await verifyIgLinkToken({IG_LINK_TOKEN_SECRET:'wrong-fake-secret'},token,now)).toBeNull();
  });
});
